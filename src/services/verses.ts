/** Couplets that belong to a festival day. */
const FESTIVAL_VERSES: Partial<Record<FestivalKey, Verse>> = {
  nowruz: V('حافظ', 'ز کوی یار می‌آید نسیم باد نوروزی', 'از این باد ار مدد خواهی چراغ دل برافروزی'),
  sizdah: V('خیام', 'بر سبزه نشین و خوش بزی روزی چند', 'زان پیش که سبزه بردمد از خاکت'),
  yalda: V('حافظ', 'صحبت حکام ظلمت شب یلداست', 'نور ز خورشید جوی بو که برآید'),
};

/** Day of the Iranian year, 1..366. */
function dayOfYear(date: Date): number {
  const [, m, d] = toJalali(date);
  return m <= 6 ? (m - 1) * 31 + d : 186 + (m - 7) * 30 + d;
}

/** The couplet of the day, following the Iranian calendar. Everyone sees the same line on the same day. */
export function verseOfDay(date: Date = new Date()): Verse {
  const fest = festivalAt(date);
  const special = fest ? FESTIVAL_VERSES[fest.key] : undefined;
  if (special) return special;
  const [y] = toJalali(date);
  return VERSES[(dayOfYear(date) + y * 7) % VERSES.length];
}
